export async function getRegistrations({
  participantName = '',
  type = '',
  status = '',
  page = 1,
  pageSize = 10,
} = {}) {
  let filtered = [...registrations];

  if (participantName.trim()) {
    filtered = filtered.filter((item) =>
      item.participantName
        .toLowerCase()
        .includes(participantName.trim().toLowerCase())
    );
  }

  if (type) {
    filtered = filtered.filter((item) => item.registrationType === type);
  }

  if (status) {
    filtered = filtered.filter((item) => item.status === status);
  }

  const totalCount = filtered.length;
  const totalPages = Math.ceil(totalCount / pageSize);
  const start = (page - 1) * pageSize;

  return {
    items: filtered.slice(start, start + pageSize),
    page,
    pageSize,
    totalCount,
    totalPages,
  };
}

export async function getSummary() {
  const totalRegistrations = registrations.length;
  const confirmed = registrations.filter(
    (item) => item.status === 'Confirmed'
  ).length;
  const checkedIn = registrations.filter(
    (item) => item.status === 'CheckedIn'
  ).length;
  const pending = registrations.filter(
    (item) => item.status === 'Pending'
  ).length;
  const cancelled = registrations.filter(
    (item) => item.status === 'Cancelled'
  ).length;

  const totalFees = registrations.reduce(
    (sum, item) => sum + item.registrationFee,
    0
  );
  const totalPayments = registrations.reduce(
    (sum, item) => sum + item.amountPaid,
    0
  );

  return {
    totalRegistrations,
    confirmed,
    checkedIn,
    pending,
    cancelled,
    totalFees,
    totalPayments,
    uncollectedPayments: totalFees - totalPayments,
  };
}